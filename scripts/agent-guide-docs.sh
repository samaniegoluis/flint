#!/usr/bin/env bash
# Writes the docs site's copies of `flint agent-guide` (milestone 77), so the site and the
# CLI print the same text:
#   - the agent guide page; its title comes from the frontmatter, so the guide's own `# `
#     heading is left out;
#   - the landing demo's data/agent-guide.json, what `flint --json agent-guide` prints,
#     from which the demo's `flint agent-guide` prints the same text and JSON.
#
#   scripts/agent-guide-docs.sh           # rewrite both from build/flint
#   scripts/agent-guide-docs.sh --check   # exit 1 when either differs (cli-e2e runs it)
#
# FLINT_BIN picks another binary (default build/flint).
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
flint="${FLINT_BIN:-$root/build/flint}"
page="$root/site/src/content/docs/guides/agent-guide.md"
demo="$root/site/src/demo/data/agent-guide.json"

render() {
  cat <<'HEAD'
---
title: The agent guide
description: What `flint agent-guide` prints for an AI agent, the CLI reference and how to work with Flint, generated from the CLI itself.
---

<!-- Generated by scripts/agent-guide-docs.sh from `flint agent-guide`. Do not edit by hand. -->

HEAD
  "$flint" agent-guide | tr -d '\r' | sed '1{/^# /d;}' | sed '1{/^$/d;}'
}

render_demo() {
  "$flint" --json agent-guide | tr -d '\r' | python3 -c 'import json, sys; d = json.load(sys.stdin); print(json.dumps({"_comment": "Generated by scripts/agent-guide-docs.sh from `flint --json agent-guide`. Do not edit by hand.", **d}, indent="\t", ensure_ascii=False))'
}

if [[ "${1:-}" == "--check" ]]; then
  status=0
  for pair in "$page:render" "$demo:render_demo"; do
    file="${pair%%:*}"; fn="${pair##*:}"
    if ! diff -u "$file" <("$fn") >/dev/null 2>&1; then
      diff -u "$file" <("$fn") 2>&1 | head -40 >&2
      echo "agent-guide-docs: $file differs from \`flint agent-guide\`; run scripts/agent-guide-docs.sh" >&2
      status=1
    fi
  done
  exit "$status"
fi
render > "$page"
render_demo > "$demo"
echo "wrote $page and $demo"
