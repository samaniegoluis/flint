//   node scripts/strength-words.js package/lib/frequency_lists.js > src/domain/strength_words.cf
const f = require(process.argv[2]);
const take = [["passwords",30000],["english_wikipedia",30000],["us_tv_and_film",30000],["surnames",10000],["female_names",4000],["male_names",1000]];
