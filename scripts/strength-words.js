// generated from zxcvbn 4.4.2's frequency lists (MIT, (c) 2012-2016 Dan Wheeler and
// Dropbox, Inc.): each list whole, its entries of lowercase letters and digits only,
// in rank order, separated by spaces. Chunks stay under 12 KB so every C++ compiler
// takes them as one string literal. Generated by scripts/strength-words.js: do not edit by
// hand.
