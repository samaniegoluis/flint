#!/bin/sh
# Flint's version, read from git (milestone 32, D-077).
#
#   scripts/version.sh            prints it: 0.1.0 on a tag, 0.1.0-3-gabc1234 three commits
#                                 after it, a "-dirty" suffix with uncommitted changes,
#                                 0.0.0-dev with no git or no release tag yet
#   scripts/version.sh --write    also writes src/drivers/version/version.cf (gitignored)
#                                 when it changed; build.cf runs this before every build
#
# FLINT_VERSION in the environment wins over git: a build from a tarball, or one whose
# shell has no git (the owner's Windows branch), sets it there.
#
# A test package (milestone 54, `scripts/package.sh linux --test-feed`) is built with
# FLINT_BUILD_TEST_FEED (a feed on 127.0.0.1 or localhost) and FLINT_BUILD_TEST_KEY (its
# Ed25519 public key, hex), compiled in as UPDATE_TEST_FEED / UPDATE_TEST_KEY_HEX. Every
# other build has both empty, so no file or variable can point it elsewhere
# (Principles 15 and 17); release-draft.sh refuses a package built this way.
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)

v="${FLINT_VERSION:-}"
if [ -z "$v" ]; then
  # Only release tags (vX.Y.Z): the repo has other tags (demo-2026-11-05).
  v=$(git -C "$root" describe --tags --match 'v[0-9]*' --dirty 2>/dev/null || true)
  v="${v#v}"
fi
[ -n "$v" ] || v="0.0.0-dev"

if [ "${1:-}" = "--write" ]; then
  out="$root/src/drivers/version/version.cf"
  mkdir -p "$(dirname "$out")"
  feed="${FLINT_BUILD_TEST_FEED:-}" key="${FLINT_BUILD_TEST_KEY:-}"
  if [ -n "$feed$key" ]; then
    case "$feed" in
      http://127.0.0.1:*|http://localhost:*) ;;
      *) echo "version.sh: FLINT_BUILD_TEST_FEED must be on 127.0.0.1 or localhost" >&2; exit 1 ;;
    esac
    printf '%s' "$key" | grep -Eq '^[0-9a-f]{64}$' \
      || { echo "version.sh: FLINT_BUILD_TEST_KEY must be 64 hex characters" >&2; exit 1; }
  fi
  body="package version

// Generated by scripts/version.sh before every build (milestone 32): do not edit, and
// do not commit (.gitignore). The version comes from git, or FLINT_VERSION when set.
FLINT_VERSION: str = \"$v\"

// Empty except in a test package (milestone 54): its local feed and that feed's key.
UPDATE_TEST_FEED: str = \"$feed\"
UPDATE_TEST_KEY_HEX: str = \"$key\""
  if [ ! -f "$out" ] || [ "$(cat "$out")" != "$body" ]; then
    printf '%s\n' "$body" > "$out"
  fi
fi
printf '%s\n' "$v"
