#!/bin/sh
# Flint's version, read from git (milestone 32, D-077).
#
#   scripts/version.sh            prints it: 0.1.0 on a tag, 0.1.0-3-gabc1234 three commits
#                                 after it, a "-dirty" suffix with uncommitted changes,
#                                 0.0.0-dev with no git or no release tag yet
#   scripts/version.sh --write    also writes src/drivers/version/version.cf (gitignored)
#                                 when it changed; build.cf runs this before every build
#
# FLINT_VERSION in the environment wins over git: a build from a tarball, or one whose
# shell has no git (the owner's Windows branch), sets it there.
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)

v="${FLINT_VERSION:-}"
if [ -z "$v" ]; then
  # Only release tags (vX.Y.Z): the repo has other tags (demo-2026-11-05).
  v=$(git -C "$root" describe --tags --match 'v[0-9]*' --dirty 2>/dev/null || true)
  v="${v#v}"
fi
[ -n "$v" ] || v="0.0.0-dev"

if [ "${1:-}" = "--write" ]; then
  out="$root/src/drivers/version/version.cf"
  mkdir -p "$(dirname "$out")"
  body="package version

// Generated by scripts/version.sh before every build (milestone 32): do not edit, and
// do not commit (.gitignore). The version comes from git, or FLINT_VERSION when set.
FLINT_VERSION: str = \"$v\""
  if [ ! -f "$out" ] || [ "$(cat "$out")" != "$body" ]; then
    printf '%s\n' "$body" > "$out"
  fi
fi
printf '%s\n' "$v"
